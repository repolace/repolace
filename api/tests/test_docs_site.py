"""The public documentation pages at /documentation/: served, within the site's CSP, free of private details, and current.

The HTML is generated by `docs/tools/build_site.py` from `docs/*.md` and committed under `repolace_api/site/docs_site/`.
"""

import importlib.util
import json
import re
from pathlib import Path

import httpx
import pytest
from repolace_api.config import SiteSettings
from repolace_api.site import create_site_app

HOST = "repolace.example.test"
ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / "api" / "repolace_api" / "site"
DOCS_SITE = SITE / "docs_site"
HTML_FILES = sorted(DOCS_SITE.rglob("*.html"))
ALL_FILES = sorted(p for p in DOCS_SITE.rglob("*") if p.is_file())
PAGE_URLS = ["/documentation/"] + [f"/documentation/{p.parent.name}/" for p in HTML_FILES if p.parent != DOCS_SITE]
SHARED_TOKENS = "page|surface|ink|ink-2|muted|grid|axis|border|wash|accent|accent-ink|shadow|serif|sans|mono|gutter|ease"

pytestmark = pytest.mark.anyio


def client() -> httpx.AsyncClient:
    app = create_site_app(SiteSettings(site_allowed_hosts=HOST, _env_file=None))
    return httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url=f"http://{HOST}")


def ids(path: Path) -> set[str]:
    return set(re.findall(r'\bid="([^"]+)"', path.read_text()))


def test_the_index_page_exists_and_every_page_has_a_title_and_one_h1():
    assert (DOCS_SITE / "index.html").is_file()
    for path in HTML_FILES:
        text = path.read_text()
        assert re.search(r"<title>[^<]+ - repolace documentation</title>", text), path
        assert text.count("<h1") == 1, path


@pytest.mark.parametrize("url", PAGE_URLS)
async def test_each_public_page_is_served(url):
    async with client() as c:
        resp = await c.get(url)
    assert resp.status_code == 200
    assert "text/html" in resp.headers["content-type"]
    assert "<h1" in resp.text and 'class="topbar"' in resp.text and 'id="theme"' in resp.text


async def test_the_bare_path_redirects_and_fastapi_docs_stay_off():
    async with client() as c:
        moved = await c.get("/documentation")
        docs = await c.get("/docs")
    assert moved.status_code in (301, 307, 308) and moved.headers["location"].endswith("/documentation/")
    assert docs.status_code == 404


async def test_assets_and_internal_links_resolve_to_served_files_and_real_anchors():
    async with client() as c:
        for path in HTML_FILES:
            text = path.read_text()
            targets = set(re.findall(r'(?:href|src)="(/[^"]*)"', text))
            for target in targets:
                url, _, fragment = target.partition("#")
                resp = await c.get(url.split("?")[0])
                assert resp.status_code == 200, f"{path.relative_to(DOCS_SITE)} links to {target}"
                if fragment and url.startswith("/documentation/") and url.endswith("/"):
                    page = DOCS_SITE / url.removeprefix("/documentation/") / "index.html"
                    assert fragment in ids(page), f"{path.relative_to(DOCS_SITE)}: no #{fragment} in {url}"
            for fragment in re.findall(r'href="#([^"]+)"', text):
                assert fragment in ids(path), f"{path.relative_to(DOCS_SITE)}: dead in-page link #{fragment}"


async def test_the_site_nav_and_footer_link_to_the_documentation():
    async with client() as c:
        home = (await c.get("/")).text
    assert home.count('href="/documentation/"') == 3  # top bar, phone menu, footer
    for name in ("benchmark_site", "retrieval_site"):
        assert 'href="/documentation/"' in (SITE / name / "js" / "main.js").read_text()


def test_pages_fit_the_content_security_policy():
    """The site allows only its own external script and style: no inline script or style, no handlers, no remote resources."""
    for path in HTML_FILES:
        text = path.read_text()
        assert not re.search(r"<script(?![^>]*\bsrc=)", text), f"inline script in {path}"
        assert " style=" not in text and "<style" not in text, f"inline style in {path}"
        assert not re.search(r"\son[a-z]+\s*=", text), f"event handler in {path}"
        assert not re.search(r"""<(?:link|script|img|iframe)[^>]+(?:src|href)=["'](?:https?:)?//""", text), path
    for path in (p for p in ALL_FILES if p.suffix == ".svg"):
        svg = path.read_text()
        assert "<script" not in svg and not re.search(r"\son[a-z]+\s*=", svg) and "<foreignObject" not in svg, path
        assert "<title" in svg and "<desc" in svg and "viewBox" in svg and not re.search(r'<svg[^>]*\swidth="', svg), path
        assert len(svg.encode()) < 12 * 1024, path
        assert not re.search(r"""(?:href|src)=["']https?://""", svg), path


def test_docs_stylesheet_reuses_the_report_tokens_and_redefines_none_of_them():
    css = (DOCS_SITE / "docs.css").read_text()
    assert '@import url("/benchmark/style.css");' in css
    assert not re.search(rf"(?<![\w-])--(?:{SHARED_TOKENS})\s*:", css)
    assert "@font-face" not in css and "http" not in css
    page = (DOCS_SITE / "index.html").read_text()
    assert "/benchmark/js/theme-init.js" in page and "/documentation/docs.js" in page


def test_no_private_details_in_any_published_file():
    patterns = {
        "a 12-digit account id": r"(?<!\d)\d{12}(?!\d)",
        "an ARN": r"arn:aws",
        "an EC2 instance id": r"\bi-0[0-9a-f]{8,17}\b",
        "a UUID (tunnel or task id)": r"\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b",
        "a secret name": r"secretsmanager",
    }
    for path in ALL_FILES:
        text = path.read_text()
        for what, pattern in patterns.items():
            assert not re.search(pattern, text, re.IGNORECASE), f"{what} in {path.relative_to(DOCS_SITE)}"
        for block in re.findall(r"<(?:pre|code)[^>]*>.*?</(?:pre|code)>", text, re.DOTALL):
            assert "rounakkumarsingh" not in block, f"a hostname in a code block of {path.relative_to(DOCS_SITE)}"


def test_headline_numbers_match_the_analysis():
    results = json.loads((ROOT / "BENCHMARK" / "analysis" / "results.json").read_text())["headlines"]
    known = {(h["passed"], h["planned"]) for h in results.values() if "planned" in h}
    rates = {h["rate"] for h in results.values()}
    assert (29, 54) in known and (35, 54) in known
    for path in HTML_FILES:
        text = re.sub(r"<[^>]*>", "", path.read_text())
        for passed, planned in re.findall(r"\b(\d+)/(\d+)\b", text):
            if planned == "54":
                assert (int(passed), 54) in known, f"{passed}/54 in {path.relative_to(DOCS_SITE)} is not in results.json"
        for rate in re.findall(r"\b(\d{2}\.\d)%", text):
            if rate in {"53.7", "64.8", "29.0"}:
                assert float(rate) in rates, f"{rate}% in {path.relative_to(DOCS_SITE)}"


