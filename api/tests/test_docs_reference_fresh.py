"""The generated pages under docs/reference match what the generator produces from the code now.

If this fails, run `python docs/tools/gen_reference.py` and commit the result.
"""

import importlib.util
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
GENERATOR = ROOT / "docs" / "tools" / "gen_reference.py"


def _load():
    spec = importlib.util.spec_from_file_location("docs_gen_reference", GENERATOR)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_reference_pages_are_fresh() -> None:
    if not GENERATOR.exists():
        pytest.skip("docs/tools/gen_reference.py is not in this checkout")
    pages = _load().render_all()
    assert pages, "the generator produced no pages"
    stale = [rel for rel, text in sorted(pages.items()) if not (ROOT / rel).is_file() or (ROOT / rel).read_text(encoding="utf-8") != text]
    assert not stale, f"stale generated pages (run python docs/tools/gen_reference.py): {stale}"


def test_generation_is_deterministic_and_marked() -> None:
    if not GENERATOR.exists():
        pytest.skip("docs/tools/gen_reference.py is not in this checkout")
    module = _load()
    first = module.render_all()
    assert first == module.render_all()
    for rel, text in first.items():
        assert text.startswith("<!-- Generated by docs/tools/gen_reference.py"), rel
