"""Generate docs/reference/*.md from the code. Standard library only; nothing is imported or run.

    python docs/tools/gen_reference.py           write the pages
    python docs/tools/gen_reference.py --check   exit 1, listing pages that differ from the code

Everything is read with `ast`, `tomllib` or plain text, so it works in CI with no .env, no database
and none of the project's dependencies installed. Output is sorted, so two runs give the same bytes.
"""

from __future__ import annotations

import ast
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BANNER = "<!-- Generated by docs/tools/gen_reference.py from the code. Do not edit by hand. -->"
HTTP_METHODS = {"get", "post", "put", "patch", "delete", "head", "options"}


def _page(title: str, intro: str, body: list[str]) -> str:
    return "\n".join([BANNER, "", f"# {title}", "", intro, "", *body]).rstrip() + "\n"


def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _table(header: list[str], rows: list[list[object]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(" --- " for _ in header) + "|"]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return lines


def _parse(path: Path) -> ast.Module:
    return ast.parse(path.read_text(encoding="utf-8"), filename=str(path))


def _rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


# --- migrations -------------------------------------------------------------------------------


def _assigned(tree: ast.Module, name: str) -> object:
    for node in tree.body:
        target = node.target if isinstance(node, ast.AnnAssign) else None
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
            target = node.targets[0]
        if isinstance(target, ast.Name) and target.id == name and node.value is not None:
            return ast.literal_eval(node.value)
    return None


def render_migrations() -> str:
    rows, downs = [], set()
    for path in sorted((ROOT / "api/alembic/versions").glob("*.py")):
        tree = _parse(path)
        rev, down = _assigned(tree, "revision"), _assigned(tree, "down_revision")
        summary = (ast.get_docstring(tree) or "").strip().splitlines()[:1]
        downs.add(down)
        rows.append([f"`{rev}`", f"`{down}`" if down else "none", summary[0] if summary else "", f"`{path.name}`"])
    rows.sort(key=lambda r: r[0])
    heads = [r[0] for r in rows if r[0].strip("`") not in downs]
    body = [f"Head: {', '.join(heads)}", "", *_table(["Revision", "Down revision", "Summary", "File"], rows)]
    return _page("Alembic migrations", "Every revision in `api/alembic/versions`, read statically.", body)


# --- tables -----------------------------------------------------------------------------------


def _is_optional(annotation: ast.expr) -> bool:
    return "None" in ast.unparse(annotation)


def render_tables() -> str:
    tree = _parse(ROOT / "shared/repolace_shared/db/models.py")
    sections: dict[str, list[str]] = {}
    for cls in (n for n in tree.body if isinstance(n, ast.ClassDef)):
        table = next(
            (s.value.value for s in cls.body
             if isinstance(s, ast.Assign) and getattr(s.targets[0], "id", "") == "__tablename__"
             and isinstance(s.value, ast.Constant)),
            None,
        )
        if table is None:
            continue
        rows = []
        for stmt in cls.body:
            call = stmt.value if isinstance(stmt, ast.AnnAssign) else None
            if not (isinstance(call, ast.Call) and ast.unparse(call.func) == "mapped_column"):
                continue
            kwargs = {k.arg: k.value for k in call.keywords}
            typ = ast.unparse(call.args[0]) if call.args else ast.unparse(stmt.annotation)
            if "nullable" in kwargs:
                nullable = ast.unparse(kwargs["nullable"]) != "False"
            elif "primary_key" in kwargs:
                nullable = False
            else:
                nullable = _is_optional(stmt.annotation)
            rows.append([f"`{stmt.target.id}`", f"`{typ}`", "yes" if nullable else "no"])
        sections[table] = [f"## `{table}`", "", *_table(["Column", "Type", "Nullable"], rows), ""]
    body = [line for name in sorted(sections) for line in sections[name]]
    intro = "Tables and columns declared in `shared/repolace_shared/db/models.py`, read statically. Types are as written in the model."
    return _page("Database tables", intro, body)


# --- environment ------------------------------------------------------------------------------


def _compose_env_files() -> dict[str, list[str]]:
    """env file name -> services that list it, from the `services:` block of the compose file as text."""
    readers: dict[str, list[str]] = {}
    in_services, service = False, None
    for line in (ROOT / "infra/docker-compose.yml").read_text().splitlines():
        if re.match(r"^\S", line):
            in_services, service = line.startswith("services:"), None
        elif in_services and (m := re.match(r"^  ([\w-]+):\s*$", line)):
            service = m.group(1)
        elif in_services and service and (m := re.match(r"^\s+- path:\s*(\S+)", line)):
            readers.setdefault(m.group(1), []).append(service)
    return readers


def _env_vars(path: Path) -> list[tuple[str, list[str]]]:
    found, comments = [], []
    for raw in path.read_text().splitlines():
        line = raw.strip()
        if line.startswith("#"):
            comments.append(line.lstrip("#").strip())
        elif m := re.match(r"^([A-Za-z_][A-Za-z0-9_]*)=", line):
            found.append((m.group(1), comments))
            comments = []
        else:
            comments = []
    return found


def render_env() -> str:
    readers = _compose_env_files()
    files = ["infra/api.env.example", "infra/worker.env.example", "infra/site.env.example", ".env.example"]
    body = []
    for name in files:
        live = Path(name).name.replace(".example", "")
        services = readers.get(live)
        who = "compose services: " + ", ".join(f"`{s}`" for s in sorted(services)) if services else (
            "no compose service; read by host processes (CLI, benchmark runner, tests)")
        body += [f"## `{name}`", "", f"Read by {who}.", ""]
        rows = [[f"`{var}`", " ".join(c)] for var, c in _env_vars(ROOT / name)]
        body += _table(["Variable", "Comment"], rows) + [""]
    intro = "Variable names and their comments from each example file. Values are never shown."
    return _page("Environment variables", intro, body)


# --- commands ---------------------------------------------------------------------------------


def _flags(path: Path) -> list[list[object]]:
    rows = []
    for node in ast.walk(_parse(path)):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "add_argument":
            names = [a.value for a in node.args if isinstance(a, ast.Constant) and isinstance(a.value, str)]
            kw = {k.arg: k.value for k in node.keywords}
            help_text = ast.literal_eval(kw["help"]) if "help" in kw and _is_literal(kw["help"]) else ""
            default = f"`{ast.unparse(kw['default'])}`" if "default" in kw else ""
            rows.append([f"`{', '.join(names)}`", default, help_text])
    return rows


def _is_literal(node: ast.expr) -> bool:
    try:
        ast.literal_eval(node)
    except ValueError:
        return False
    return True


def render_commands() -> str:
    scripts = []
    for toml in sorted(ROOT.glob("*/pyproject.toml")) + [ROOT / "pyproject.toml"]:
        for name, target in tomllib.loads(toml.read_text()).get("project", {}).get("scripts", {}).items():
            scripts.append([f"`{name}`", f"`{target}`", f"`{_rel(toml)}`"])
    scripts.sort()
    body = ["## Console scripts", "", *_table(["Command", "Entry point", "Declared in"], scripts), ""]

    eval_cli = _parse(ROOT / "eval/harness/cli.py")
    subs = _assigned_dict(eval_cli, "SUBCOMMANDS")
    body += ["## `repolace-eval`", ""]
    for name in sorted(subs):
        module, summary = subs[name]
        path = ROOT / "eval" / (module.replace(".", "/") + ".py")
        body += [f"### `repolace-eval {name}`", "", summary, ""]
        rows = _flags(path) if path.exists() else []
        body += (_table(["Argument", "Default", "Help"], rows) if rows else ["No arguments."]) + [""]

    body += ["## `repolace-run-task`", ""]
    body += _table(["Argument", "Default", "Help"], _flags(ROOT / "pipeline/repolace_pipeline/cli.py"))
    intro = "Console scripts from every `pyproject.toml`, and the arguments declared with `add_argument` (read statically, nothing is run)."
    return _page("Commands", intro, body)


def _assigned_dict(tree: ast.Module, name: str) -> dict[str, tuple[str, str]]:
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and getattr(node.target, "id", "") == name:
            return ast.literal_eval(node.value)
    raise KeyError(name)


# --- routes -----------------------------------------------------------------------------------

API = ROOT / "api/repolace_api"
# Globbed, not listed, so a new router module (sign-in, billing) is picked up without editing this file.
PRIVATE_FILES = [API / "main.py", *sorted((API / "routes").glob("*.py")), *sorted((API / "ui").glob("*.py"))]
SITE_FILES = [API / "site/app.py"]


def _str(node: ast.expr | None) -> str | None:
    return node.value if isinstance(node, ast.Constant) and isinstance(node.value, str) else None


def _scan_routes(path: Path) -> list[list[str]]:
    """Routes declared by decorators, `add_api_route` and `mount` in one file."""
    tree = _parse(path)
    prefixes = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Call) and ast.unparse(node.value.func) == "APIRouter":
            prefixes[node.targets[0].id] = next((_str(k.value) for k in node.value.keywords if k.arg == "prefix"), "") or ""
    prefixes["app"] = ""
    found = []
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef):
            for dec in node.decorator_list:
                if (isinstance(dec, ast.Call) and isinstance(dec.func, ast.Attribute) and dec.func.attr in HTTP_METHODS
                        and isinstance(dec.func.value, ast.Name) and dec.func.value.id in prefixes and _str(dec.args[0] if dec.args else None) is not None):
                    found.append([dec.func.attr.upper(), prefixes[dec.func.value.id] + _str(dec.args[0]), node.name, _rel(path)])
        elif isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.args and _str(node.args[0]) is not None:
            if node.func.attr == "add_api_route":
                methods = next((ast.literal_eval(k.value) for k in node.keywords if k.arg == "methods"), ["GET"])
                handler = ast.unparse(node.args[1]) if len(node.args) > 1 else ""
                found += [[m, _str(node.args[0]), handler, _rel(path)] for m in methods]
            elif node.func.attr == "mount":
                found.append(["mount", _str(node.args[0]) + "/*", "static files", _rel(path)])
    return found


def render_routes() -> str:
    def section(title: str, files: list[Path]) -> list[str]:
        rows = sorted((r for f in files for r in _scan_routes(f)), key=lambda r: (r[1], r[0]))
        return [f"## {title}", "", *_table(["Method", "Path", "Handler", "Defined in"], rows), ""]

    body = section("Private API (`repolace_api.main:app`)", PRIVATE_FILES)
    body += ["FastAPI also serves `/docs`, `/redoc` and `/openapi.json` on this app.", ""]
    body += section("Public site (`repolace_api.site.main:app`)", SITE_FILES)
    body += ["The public site mounts no router from `repolace_api.routes` and not the UI; it serves no API docs.", ""]
    intro = ("Method: a static `ast` scan of the route decorators, `add_api_route` and `mount` calls in the files listed in "
             "`docs/tools/gen_reference.py` (nothing is imported, so no settings or secrets are needed). "
             "Router prefixes are applied; `mount` rows are static-file directories.")
    return _page("HTTP routes", intro, body)


# --- driver -----------------------------------------------------------------------------------


def render_all() -> dict[str, str]:
    """Relative path (from the repository root) -> generated content."""
    return {
        "docs/reference/migrations.md": render_migrations(),
        "docs/reference/tables.md": render_tables(),
        "docs/reference/env.md": render_env(),
        "docs/reference/commands.md": render_commands(),
        "docs/reference/routes.md": render_routes(),
    }


def main(argv: list[str] | None = None) -> int:
    check = "--check" in (sys.argv[1:] if argv is None else argv)
    pages = render_all()
    stale = [rel for rel, text in pages.items()
             if not (ROOT / rel).exists() or (ROOT / rel).read_text(encoding="utf-8") != text]
    if check:
        for rel in stale:
            print(f"stale: {rel}", file=sys.stderr)
        return 1 if stale else 0
    for rel, text in pages.items():
        (ROOT / rel).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / rel).write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
